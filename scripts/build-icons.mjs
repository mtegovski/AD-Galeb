// Builds src/icons.css: every Font Awesome icon the templates use (`<i class="fas fa-…">`),
// drawn by the stylesheet itself so icons show instantly without loading the Font Awesome kit.
// Run `npm run icons` after using a new fa-* icon.
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import * as solid from '@fortawesome/free-solid-svg-icons';

const SRC = new URL('../src/', import.meta.url).pathname;
// Classes that are not icons
const NOT_ICONS = new Set(['fa-spin']);

const used = new Set();
for (const file of readdirSync(SRC, {recursive: true})) {
  if (!/\.(html|ts)$/.test(file)) continue;
  for (const [cls] of readFileSync(join(SRC, file), 'utf8').matchAll(/\bfa-[a-z0-9-]+/g)) {
    if (!NOT_ICONS.has(cls)) used.add(cls);
  }
}

// fa-map-marker-alt -> faMapMarkerAlt (old names are exported as aliases too)
const exportName = cls => cls.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const rules = [...used].sort().map(cls => {
  const def = solid[exportName(cls)];
  if (!def) throw new Error(`${cls} is not a Font Awesome Free solid icon`);
  const [width, height, , , path] = def.icon;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}"><path d="${path}"/></svg>`;
  return `  .${cls} {\n    --fa-icon: url("data:image/svg+xml,${encodeURIComponent(svg)}");\n    width: ${+(width / height).toFixed(4)}em;\n  }`;
});

const {version} = JSON.parse(
  readFileSync(new URL('../node_modules/@fortawesome/free-solid-svg-icons/package.json', import.meta.url), 'utf8'),
);

writeFileSync(join(SRC, 'icons.css'), `/* Generated by scripts/build-icons.mjs (npm run icons) — do not edit by hand.
   Icons: Font Awesome Free ${version} by Fonticons, Inc., CC BY 4.0 — https://fontawesome.com/license/free */

/* In the components layer so Tailwind utilities on an icon (w-5, text-3xl, rotate-90…) still win */
@layer components {
  .fas {
    display: inline-block;
    height: 1em;
    vertical-align: -0.125em;
    background-color: currentColor;
    -webkit-mask: var(--fa-icon) center / contain no-repeat;
    mask: var(--fa-icon) center / contain no-repeat;
  }

  .fa-spin {
    animation: fa-spin 2s linear infinite;
  }

  @keyframes fa-spin {
    to {
      transform: rotate(360deg);
    }
  }

${rules.join('\n\n')}
}
`);

console.log(`icons.css: ${used.size} icons`);
